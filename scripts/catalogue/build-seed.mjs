/**
 * Generates, from scripts/catalogue/starter-data.mjs:
 *   supabase/seed/catalogue/starter-catalogue.json  — importable through the admin portal
 *   supabase/seed/catalogue.sql                     — loaded by `supabase db reset` / the seed step
 *
 * Both go through the same import function as admin uploads, so seeded
 * records start as pending_review and need admin approval.
 *
 * Usage: npm run catalogue:build   (CI checks the outputs are up to date)
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import rows from './starter-data.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

export function buildJson() {
  return JSON.stringify(rows, null, 2) + '\n';
}

export function buildSql() {
  const json = JSON.stringify(rows);
  if (json.includes('$itm_catalogue$')) throw new Error('Data contains the SQL dollar-quote tag');
  return [
    '-- GENERATED by scripts/catalogue/build-seed.mjs from scripts/catalogue/starter-data.mjs. Do not edit by hand.',
    '-- Imports the generic starter catalogue as pending_review (approve in the admin portal).',
    "select private.catalogue_import_core($itm_catalogue$" + json + "$itm_catalogue$::jsonb, 'starter-catalogue.json', 'seed', false, null);",
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(ROOT, 'supabase', 'seed', 'catalogue', 'starter-catalogue.json'), buildJson());
  writeFileSync(join(ROOT, 'supabase', 'seed', 'catalogue.sql'), buildSql());
  console.log(`Wrote ${rows.length} catalogue rows.`);
}
